export const productProvisioningOperations = pgTable("product_provisioning_operations", {
  id: uuid("id").defaultRandom().primaryKey(),
  schemaVersion: varchar("schema_version", { length: 16 }).notNull(),
  source: varchar("source", { length: 24 }).notNull(),
  eventId: uuid("event_id").notNull(),
  correlationId: uuid("correlation_id").notNull(),
  idempotencyKey: varchar("idempotency_key", { length: 200 }).notNull(),
  requestFingerprint: varchar("request_fingerprint", { length: 64 }).notNull(),
  externalCustomerId: varchar("external_customer_id", { length: 120 }).notNull(),
  externalOrderId: varchar("external_order_id", { length: 120 }).notNull(),
  offerId: varchar("offer_id", { length: 120 }).notNull(),
  offerVersion: varchar("offer_version", { length: 64 }).notNull(),
  productId: varchar("product_id", { length: 120 }).notNull(),
  productVersion: varchar("product_version", { length: 64 }).notNull(),
  solutionId: varchar("solution_id", { length: 120 }).notNull(),
  solutionVersion: varchar("solution_version", { length: 64 }).notNull(),
  templateId: varchar("template_id", { length: 120 }).notNull(),
  templateVersion: varchar("template_version", { length: 64 }).notNull(),
  requestedDomain: varchar("requested_domain", { length: 253 }),
  tenantId: uuid("tenant_id").references(() => tenants.id, { onDelete: "restrict" }),
  installationId: uuid("installation_id"),
  status: varchar("status", { length: 32 }).notNull().default("accepted"),
  currentStep: varchar("current_step", { length: 80 }),
  failureCode: varchar("failure_code", { length: 80 }),
  failureRetryable: boolean("failure_retryable"),
  failureDisposition: varchar("failure_disposition", { length: 24 }),
  leaseToken: uuid("lease_token"),
  leaseExpiresAt: timestamp("lease_expires_at", { withTimezone: true }),
  fencingToken: bigint("fencing_token", { mode: "number" }).notNull().default(0),
  workerId: varchar("worker_id", { length: 128 }),
  attemptCount: integer("attempt_count").notNull().default(0),
  retryAfterAt: timestamp("retry_after_at", { withTimezone: true }),
  manualReviewNote: text("manual_review_note"),
  lastOperatorActorId: varchar("last_operator_actor_id", { length: 128 }),
  acceptedAt: timestamp("accepted_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  finishedAt: timestamp("finished_at", { withTimezone: true }),
}, (table) => [
  check("product_provisioning_operations_status_ck", sql`${table.status} in ('accepted', 'validating', 'provisioning_tenant', 'configuring_installation', 'provisioning_hosting', 'ready', 'compensating', 'compensation_required', 'compensated', 'failed')`),
  check("product_provisioning_operations_failure_ck", sql`(${table.status} = 'failed' and ${table.failureCode} is not null and ${table.failureRetryable} is not null and ${table.failureDisposition} in ('retry', 'compensate')) or (${table.status} = 'compensation_required' and ${table.failureCode} is not null and ${table.failureRetryable} is not null and ${table.failureDisposition} in ('unknown', 'compensation_failed')) or (${table.status} not in ('failed', 'compensation_required') and ${table.failureCode} is null and ${table.failureRetryable} is null and ${table.failureDisposition} is null)`),
  check("product_provisioning_operations_ready_ck", sql`${table.status} <> 'ready' or (${table.tenantId} is not null and ${table.installationId} is not null and ${table.finishedAt} is not null)`),
  unique("product_provisioning_operations_idempotency_uq").on(table.source, table.idempotencyKey),
  unique("product_provisioning_operations_event_uq").on(table.source, table.eventId),
  unique("product_provisioning_operations_order_uq").on(table.source, table.externalOrderId),
  check("product_provisioning_operations_fingerprint_ck", sql`${table.requestFingerprint} ~ '^[a-f0-9]{64}$'`),
  foreignKey({ columns: [table.installationId, table.tenantId], foreignColumns: [productInstallations.id, productInstallations.tenantId], name: "product_provisioning_operations_installation_fk" }),
  index("product_provisioning_operations_tenant_idx").on(table.tenantId, table.acceptedAt),
]);

export const productProvisioningStepAttempts = pgTable("product_provisioning_step_attempts", {
  id: uuid("id").defaultRandom().primaryKey(),
  operationId: uuid("operation_id").notNull().references(() => productProvisioningOperations.id, { onDelete: "restrict" }),
  stepName: varchar("step_name", { length: 80 }).notNull(),
  direction: varchar("direction", { length: 12 }).notNull(),
  attemptNumber: integer("attempt_number").notNull(),
  status: varchar("status", { length: 16 }).notNull().default("running"),
  fencingToken: bigint("fencing_token", { mode: "number" }).notNull().default(0),
  correlationId: uuid("correlation_id"),
  effectRefs: jsonb("effect_refs").$type<Readonly<Record<string, string>>>().notNull().default({}),
  errorCode: varchar("error_code", { length: 80 }),
  retryable: boolean("retryable"),
  failureDisposition: varchar("failure_disposition", { length: 24 }),
  startedAt: timestamp("started_at", { withTimezone: true }).notNull().defaultNow(),
  finishedAt: timestamp("finished_at", { withTimezone: true }),
}, (table) => [
  unique("product_provisioning_step_attempts_number_uq").on(table.operationId, table.stepName, table.direction, table.attemptNumber),
  check("product_provisioning_step_attempts_effect_ck", sql`public.is_safe_product_provisioning_effect(${table.effectRefs})`),
  check("product_provisioning_step_attempts_status_ck", sql`${table.status} in ('running', 'succeeded', 'failed', 'unknown')`),
  check("product_provisioning_step_attempts_result_ck", sql`(${table.status} = 'running' and ${table.finishedAt} is null and ${table.errorCode} is null and ${table.retryable} is null and ${table.failureDisposition} is null) or (${table.status} = 'succeeded' and ${table.finishedAt} is not null and ${table.errorCode} is null and ${table.retryable} is null and ${table.failureDisposition} is null) or (${table.status} = 'failed' and ${table.finishedAt} is not null and ${table.errorCode} is not null and ${table.retryable} is not null and ${table.failureDisposition} in ('retry', 'compensate', 'compensation_failed')) or (${table.status} = 'unknown' and ${table.finishedAt} is not null and ${table.errorCode} is not null and ${table.retryable} is not null and ${table.failureDisposition} = 'unknown')`),
  index("product_provisioning_step_attempts_history_idx").on(table.operationId, table.startedAt),
]);

