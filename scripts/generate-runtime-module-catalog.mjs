import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { assertSupportedSchema, validateJsonSchema } from "./lib/json-schema.mjs";

const root = process.cwd();
const policyPath = "products/runtime-module-policy.json";
const policySchemaPath = "products/runtime-module-policy.schema.json";
const catalogPath = "products/catalog.json";
const outputPath = "apps/api/src/modules/admin/module-catalog.ts";

function readJson(path) {
  try {
    return JSON.parse(readFileSync(join(root, path), "utf8"));
  } catch (error) {
    throw new Error(`Could not read ${path}: ${error instanceof Error ? error.message : "invalid JSON"}`);
  }
}

function generateRuntimeCatalog() {
  const policy = readJson(policyPath);
  const policySchema = readJson(policySchemaPath);
  const catalog = readJson(catalogPath);
  assertSupportedSchema(policySchema, policySchemaPath);
  const schemaErrors = validateJsonSchema(policy, policySchema);
  if (schemaErrors.length) throw new Error(schemaErrors.join("\n"));

  const catalogModules = new Map((catalog.modules ?? []).map((module) => [module.id, module]));
  const policyIds = new Set();
  const modules = policy.modules.map((runtimePolicy) => {
    if (policyIds.has(runtimePolicy.id)) throw new Error(`Duplicate runtime module policy ID: ${runtimePolicy.id}`);
    policyIds.add(runtimePolicy.id);

    const manifestPath = `modules/${runtimePolicy.id}/manifest.json`;
    const manifest = readJson(manifestPath);
    if (manifest.id !== runtimePolicy.id) throw new Error(`${manifestPath} ID must match ${runtimePolicy.id}.`);
    if (!catalogModules.has(runtimePolicy.id) || catalogModules.get(runtimePolicy.id).classification !== "module") {
      throw new Error(`${runtimePolicy.id} must be a manifest-backed module in ${catalogPath}.`);
    }
    const expectedCatalogStatus = manifest.status === "stable" ? "implemented"
      : manifest.status === "planned" ? "planned" : "partial";
    if (catalogModules.get(runtimePolicy.id).status !== expectedCatalogStatus) {
      throw new Error(`${catalogPath} status for ${runtimePolicy.id} must match the status projection ${expectedCatalogStatus} from its module manifest.`);
    }
    if (manifest.status === "planned" && (runtimePolicy.defaultEnabled || runtimePolicy.tenantAssignable)) {
      throw new Error(`Planned module ${runtimePolicy.id} cannot be enabled or tenant-assignable.`);
    }
    if (runtimePolicy.required && !runtimePolicy.defaultEnabled) {
      throw new Error(`Required runtime module ${runtimePolicy.id} must be enabled by default.`);
    }
    if (runtimePolicy.required && runtimePolicy.tenantAssignable) {
      throw new Error(`Required runtime module ${runtimePolicy.id} cannot be tenant-assignable.`);
    }

    return {
      id: manifest.id,
      name: runtimePolicy.displayName,
      version: manifest.version,
      status: manifest.status,
      tenantModel: manifest.tenantModel,
      dependencies: runtimePolicy.entitlementDependencies,
      description: runtimePolicy.description,
      defaultEnabled: runtimePolicy.defaultEnabled,
      required: runtimePolicy.required,
      tenantAssignable: runtimePolicy.tenantAssignable,
    };
  });

  for (const module of modules) {
    for (const dependency of module.dependencies) {
      if (!policyIds.has(dependency)) {
        throw new Error(`Runtime module ${module.id} has unknown entitlement dependency ${dependency}.`);
      }
    }
  }

  const completed = new Set();
  const visiting = new Set();
  function visit(moduleId) {
    if (completed.has(moduleId)) return;
    if (visiting.has(moduleId)) throw new Error(`Runtime entitlement dependency cycle includes ${moduleId}.`);
    visiting.add(moduleId);
    for (const dependency of modules.find((module) => module.id === moduleId).dependencies) visit(dependency);
    visiting.delete(moduleId);
    completed.add(moduleId);
  }
  for (const module of modules) visit(module.id);

  const source = `// Generated by scripts/generate-runtime-module-catalog.mjs; do not edit directly.\n` +
    `export interface PlatformModuleCatalogItem {\n` +
    `  id: string;\n` +
    `  name: string;\n` +
    `  version: string;\n` +
    `  status: "planned" | "experimental" | "partial" | "stable" | "deprecated";\n` +
    `  tenantModel: "tenant-owned" | "platform-owned" | "mixed" | "not-applicable";\n` +
    `  dependencies: string[];\n` +
    `  description: string;\n` +
    `  defaultEnabled: boolean;\n` +
    `  required: boolean;\n` +
    `  tenantAssignable: boolean;\n` +
    `}\n\n` +
    `export const platformModuleCatalog: readonly PlatformModuleCatalogItem[] = ${JSON.stringify(modules, null, 2)};\n\n` +
    `export function getPlatformModule(moduleId: string): PlatformModuleCatalogItem | undefined {\n` +
    `  return platformModuleCatalog.find((module) => module.id === moduleId);\n` +
    `}\n`;
  return { modules, source };
}

try {
  const { modules, source } = generateRuntimeCatalog();
  const checkOnly = process.argv.includes("--check");
  const outputAbsolutePath = join(root, outputPath);
  if (checkOnly) {
    if (!existsSync(outputAbsolutePath) || readFileSync(outputAbsolutePath, "utf8") !== source) {
      throw new Error(`${outputPath} is stale; run pnpm modules:generate and commit the result.`);
    }
    console.log(`Runtime module catalogue is synchronized: ${modules.length} entries.`);
  } else {
    writeFileSync(outputAbsolutePath, source);
    console.log(`Generated ${outputPath} from ${policyPath} and module manifests (${modules.length} entries).`);
  }
} catch (error) {
  console.error(`[runtime-module-catalog] ${error instanceof Error ? error.message : "generation failed"}`);
  process.exitCode = 1;
}
